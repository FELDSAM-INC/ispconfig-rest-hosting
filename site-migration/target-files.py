#!/usr/bin/env python3
"""Run locally or via root SSH; verify website identity and drop root privileges."""
import json
import os
import pwd
import grp
import re
import stat
import sys


def enter(site):
    root = site['document_root']
    if not re.fullmatch(r'/var/www/clients/client[0-9]+/web[0-9]+', root):
        raise ValueError('Only canonical ISPConfig website roots are supported')
    if not re.fullmatch(r'web[0-9]+', site['system_user']) or not re.fullmatch(r'client[0-9]+', site['system_group']):
        raise ValueError('Invalid website identity')
    user = pwd.getpwnam(site['system_user'])
    group = grp.getgrnam(site['system_group'])
    if user.pw_uid == 0 or group.gr_gid == 0 or user.pw_gid != group.gr_gid:
        raise ValueError('Invalid website account')
    if root.rsplit('/', 1)[-1] != site['system_user'] or root.split('/')[-2] != site['system_group']:
        raise ValueError('Website root and account differ')
    # Check each parent; never follow customer-controlled symlinks as root.
    fd = os.open('/', os.O_RDONLY | os.O_DIRECTORY)
    try:
        for part in root.strip('/').split('/'):
            child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
            os.close(fd)
            fd = child
        os.fchdir(fd)
    finally:
        os.close(fd)
    os.setgroups([])
    os.setgid(group.gr_gid)
    os.setuid(user.pw_uid)
    # Folders of the website's domains with their own folder (created by ISPConfig with the domain).
    folders = site.get('folders', [])
    if not isinstance(folders, list) or not all(isinstance(name, str) and re.fullmatch(r'[A-Za-z0-9_][A-Za-z0-9._-]*(?:/[A-Za-z0-9_][A-Za-z0-9._-]*)*', name)
                                                and '..' not in name for name in folders):
        raise ValueError('Invalid website folders')
    for name in ['web', 'private'] + folders:
        entry = os.lstat(name)
        if not stat.S_ISDIR(entry.st_mode) or entry.st_uid != user.pw_uid:
            raise ValueError('Website folder %s is not a directory owned by the website user' % name)


if __name__ == '__main__':
    try:
        site = json.loads(sys.argv[1])
        arguments = sys.argv[2:]
        if arguments and arguments[0] == '--local-rsync':
            # rsync invokes this as its local transport: HOST rsync --server ...
            # No shell interprets these arguments and no network connection opens.
            if arguments[1:3] != ['local', 'rsync'] or len(arguments) < 4:
                raise ValueError('Invalid local rsync transport')
            arguments = arguments[3:]
        enter(site)
        if not arguments:
            print('ready')
        else:
            # Remaining arguments are generated by local rsync, not customer data.
            if arguments[0] != '--server':
                raise ValueError('Expected rsync server')
            os.execv('/usr/bin/rsync', ['rsync'] + arguments)
    except (OSError, KeyError, ValueError) as exc:
        print('Target filesystem check failed: ' + str(exc), file=sys.stderr)
        sys.exit(1)
